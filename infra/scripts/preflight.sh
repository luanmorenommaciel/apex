#!/usr/bin/env bash
# Apex infra · preflight — refuse to start the stack with missing or default credentials.
#
# A copied .env.example carries EMPTY credentials on purpose; this is the step that turns
# "forgot to set the password" into a one-line error instead of a world-readable store.
# `make up` runs it before `docker compose up`. It also renders the gitignored runtime files
# (secrets/, .local/) that keep the admin password out of every container environment.
#
# Usage:  ./scripts/preflight.sh            (reads infra/.env)
#         INFRA_ENV_FILE=/path/to/env ./scripts/preflight.sh
set -euo pipefail
cd "$(dirname "$0")/.."
ENV_FILE="${INFRA_ENV_FILE:-.env}"

fail() { echo "❌ preflight: $1"; exit 1; }

[ -f "$ENV_FILE" ] || fail "$ENV_FILE is missing — cp .env.example .env, then set CLICKHOUSE_PASSWORD and HYPERDX_API_KEY"
set -a; . "$ENV_FILE"; set +a

pw="${CLICKHOUSE_PASSWORD:-}"
[ -n "$pw" ] || fail "CLICKHOUSE_PASSWORD is empty — generate one: openssl rand -hex 24"
case "$pw" in
  apex_local_dev|change-me*|changeme*|password|secret)
    fail "CLICKHOUSE_PASSWORD is a default value — generate one: openssl rand -hex 24" ;;
esac
[ "${#pw}" -ge 16 ] || fail "CLICKHOUSE_PASSWORD is shorter than 16 characters — generate one: openssl rand -hex 24"

key="${HYPERDX_API_KEY:-}"
[[ "$key" =~ ^[0-9a-f]{64}$ ]] || fail "HYPERDX_API_KEY must be 64 hex characters (openssl rand -hex 32); got ${#key} characters"

# ── Render the gitignored runtime files the compose consumes ─────────────────────────────
# secrets/clickhouse_password   admin password as a FILE (ClickHouse: CLICKHOUSE_PASSWORD_FILE;
#                               collector: ${file:...}) so no container env carries it
# secrets/hyperdx_clickhouse_password   apex_hdx's password, generated once and kept
# .local/users.d/apex-hyperdx.xml       apex_hdx: READ-ONLY (readonly=2), SELECT on the tables
#                               HyperDX's source reads, password stored as sha256 hex only
# .local/hyperdx.env            DEFAULT_CONNECTIONS for HyperDX as apex_hdx
SECRETS_DIR="${INFRA_SECRETS_DIR:-secrets}"
LOCAL_DIR="${INFRA_LOCAL_DIR:-.local}"
umask 077
mkdir -p "$SECRETS_DIR" "$LOCAL_DIR/users.d"
printf '%s' "$pw" > "$SECRETS_DIR/clickhouse_password"
if [ ! -s "$SECRETS_DIR/hyperdx_clickhouse_password" ]; then
  openssl rand -hex 24 > "$SECRETS_DIR/hyperdx_clickhouse_password"
fi
hdx_pw="$(cat "$SECRETS_DIR/hyperdx_clickhouse_password")"
hdx_sha="$(printf '%s' "$hdx_pw" | shasum -a 256 | cut -d' ' -f1)"
cat > "$LOCAL_DIR/users.d/apex-hyperdx.xml" <<XML
<!-- GENERATED by scripts/preflight.sh — do not edit, do not commit. -->
<clickhouse>
  <profiles>
    <apex_hyperdx>
      <readonly>2</readonly>   <!-- SELECT only; may still set per-query settings HyperDX sends -->
    </apex_hyperdx>
  </profiles>
  <users>
    <apex_hdx>
      <password_sha256_hex>${hdx_sha}</password_sha256_hex>
      <networks><ip>::/0</ip></networks>
      <profile>apex_hyperdx</profile>
      <quota>default</quota>
      <grants>
        <query>GRANT SELECT ON apex.spark_events</query>
        <query>GRANT SELECT ON apex.spark_jobs_1m</query>
        <query>GRANT SELECT ON apex.findings</query>
        <query>GRANT SELECT ON apex.plan_transitions</query>
        <query>GRANT SELECT ON apex.job_conf</query>
        <query>GRANT SELECT ON apex.plan_memory</query>
        <query>GRANT SELECT ON apex.run_outcomes</query>
        <query>GRANT SELECT ON apex.fix_verifications</query>
        <query>GRANT SHOW TABLES ON apex.*</query>
      </grants>
    </apex_hdx>
  </users>
</clickhouse>
XML
cat > "$LOCAL_DIR/hyperdx.env" <<ENV
# GENERATED by scripts/preflight.sh — do not edit, do not commit.
DEFAULT_CONNECTIONS=[{"name":"Apex ClickHouse","host":"http://apex-infra-clickhouse:8123","username":"apex_hdx","password":"${hdx_pw}"}]
ENV

echo "✅ preflight ok — credentials set, no defaults; rendered $SECRETS_DIR/ and $LOCAL_DIR/ (gitignored)"
